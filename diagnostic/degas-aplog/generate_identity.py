"""Generate a fresh per-image journal seed and a non-circular source identity."""
import argparse
import datetime
import hashlib
import json
from pathlib import Path
import uuid

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = "mu/Platforms/Xiaomi/degasPkg/"
SOURCES = [PACKAGE + p for p in (
    "Include/ApJournal.h",
    "Include/WindowsObserverMap.h",
    "Drivers/DegasAcpiDxe/DegasAcpiDxe.inf",
    "Drivers/DegasAcpiDxe/Parking.S",
    "Drivers/DegasAcpiDxe/Parking.h",
    "Drivers/DegasAcpiDxe/WindowsObserver.S",
    "Drivers/DegasAcpiDxe/BugcheckMonitor.inc",
    "Drivers/DegasAcpiDxe/ApJournalCommit.inc",
    "Drivers/DegasAcpiDxe/PrcbWalk.inc",
    "Drivers/CheckpointDxe/ApJournalRetention.h",
    "Drivers/CheckpointDxe/Checkpoint.c",
    "Drivers/CheckpointDxe/OsHandoff.h",
    "Library/MemoryMapLib/MemoryMapLib.c",
    "degas.dsc",
)] + ["tools/build_degas_first_dxe.sh"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--seed", type=uuid.UUID, default=None)
    args = parser.parse_args()
    seed = args.seed or uuid.uuid4()
    hashes = {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
              for name in sorted(SOURCES)}
    # Exact canonical manifest bytes; no generated header or final image bytes.
    canonical = "".join(f"{name} {digest}\n" for name, digest in hashes.items()).encode("utf-8")
    digest = hashlib.sha256(canonical).digest()
    header = ROOT / PACKAGE / "Include/ApJournalIdentity.h"
    def array(name, data):
        return f"STATIC CONST UINT8 {name}[{len(data)}]={{" + ",".join(f"0x{x:02x}" for x in data) + "};\n"
    text = "// Generated by diagnostic/degas-aplog/generate_identity.py before the build.\n"
    text += "// Hash identifies the named source manifest, never the final image.\n"
    text += array("mDegasApJournalBuildSeed", seed.bytes)
    text += array("mDegasApJournalSourceHash", digest)
    header.write_text(text, encoding="utf-8", newline="\n")
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.write_text(json.dumps({
        "utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "build_seed": str(seed), "attempt_uuid_prefix_hex": seed.bytes[:8].hex(),
        "identity_kind": "source_manifest_sha256", "header_flags": 1,
        "source_manifest_sha256": digest.hex(), "sources": hashes,
        "hash_input_format": "sorted UTF-8 lines: relative_path + space + lowercase_sha256 + LF",
        "attempt_identity_scope": "fresh per-image seed plus retained warm-chain sequence; no uniqueness claim after RAM loss",
    }, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"header": str(header), "manifest": str(args.manifest),
                      "build_seed": str(seed), "source_manifest_sha256": digest.hex()}))


if __name__ == "__main__":
    main()
