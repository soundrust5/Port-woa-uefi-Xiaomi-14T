def array(name, data):
    lines = [f'STATIC CONST UINT8 {name}[{len(data)}] = {{']
    for at in range(0, len(data), 12):
        lines.append('  ' + ', '.join(f'0x{x:02X}' for x in data[at:at + 12]) + ',')
    return '\n'.join(lines + ['};'])


