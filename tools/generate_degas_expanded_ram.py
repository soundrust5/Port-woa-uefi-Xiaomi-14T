"""Generate a conservative RAM map from captured DT/LK/Linux exclusions.

Does not claim hardware qualification. Keeps historical and current boot
allocations, including runtime placement of dynamic carveouts, excluded.
"""
import json
import re
from pathlib import Path
from prepare_degas_windows_facts import extract, pairs
from reconcile_memory import subtract, interval

ROOT = Path(__file__).resolve().parents[1]
CAP = ROOT / 'evidence/raw/2026-10-27-degas-ram-expand'

def main():
    dt = json.loads((CAP / 'live-fdt').read_text())
    history = json.loads((ROOT / 'evidence/extracted/2026-09-14/memory-reconciliation.json').read_text())
    facts = extract(dt, history)
    reserved = [(int(a, 16), int(b, 16) + 1) for a, b in re.findall(
        r'(0x[0-9a-f]+)\.\.(0x[0-9a-f]+)', (CAP / 'memblock-reserved.txt').read_text())]
    assert reserved
    # Do not expose tiny gaps amid the kernel/firmware top-of-RAM allocations.
    reserved.append((0x32d400000, 0x340000000))
    # Current Linux placements alone do not establish secure-world ownership at
    # Mu entry. Keep the complete allocation windows until qualified separately.
    for path, node in dt['nodes'].items():
        if path.startswith('/reserved-memory/') and 'size' in node and 'reg' not in node:
            data = bytes.fromhex(node['alloc-ranges']['hex'])
            assert len(data) % 16 == 0
            for offset in range(0, len(data), 16):
                base = int.from_bytes(data[offset:offset+8], 'big')
                size = int.from_bytes(data[offset+8:offset+16], 'big')
                reserved.append((base, base+size))
    ranges = subtract(pairs(facts['additional_ram_candidates']), reserved)
    ranges = [((a + 4095) & ~4095, b & ~4095) for a, b in ranges]
    ranges = [(a, b) for a, b in ranges if a < b]
    assert any(a <= 0x140000000 and b >= 0x180000000 for a, b in ranges)
    assert len(ranges) + 30 < 255
    for a, b in ranges:
        assert 0x48080000 <= a < b <= 0x340000000
        assert all(b <= x or a >= y for x, y in reserved + pairs(facts['exclusions']))
    out = ROOT / 'mu/Platforms/Xiaomi/degasPkg/Include/ExpandedRam.inc'
    text = '// Generated by tools/generate_degas_expanded_ram.py; hardware qualification pending.\n'
    for i, (a, b) in enumerate(ranges):
        text += '{"RAM %02d",0x%xULL,0x%xULL,AddMem,SYS_MEM,SYS_MEM_CAP,Conv,WRITE_BACK},\n' % (i, a, b-a)
    out.write_text(text)
    report = dict(additional_bytes=sum(b-a for a,b in ranges),
                  ranges=[interval(a,b) for a,b in ranges],
                  exclusions=facts['exclusions'], current_reserved=[interval(a,b) for a,b in reserved],
                  hardware_verified=False)
    (CAP / 'expanded-map.json').write_text(json.dumps(report, indent=2))
    print(len(ranges), 'ranges;', report['additional_bytes']/2**30, 'GiB additional RAM')

if __name__ == '__main__': main()
